#!/usr/bin/env node
// FLUX installer build: bumps the version, then runs frontend + backend + electron + electron-builder.
//
// Version format: MAJOR.MINOR.BUILD with BUILD on 3 digits (ex: 0.1.011).
//   * every build           -> BUILD + 1                  (0.1.011 -> 0.1.012)
//   * "minor" answered Y    -> MAJOR.MINOR+1.000          (0.1.011 -> 0.2.000)
//   * "major" answered Y    -> MAJOR+1.0.000              (0.1.011 -> 1.0.000, wins over minor)
//
// Source of truth: package.json "fluxVersion" (display form). package.json "version" is kept as
// valid semver (0.1.11) because electron-builder rejects leading zeros. The bump is written
// before the build (PyInstaller / electron-builder read it) and rolled back if the build fails.
//
// Flags (skip the prompts): --minor, --major, --no-prompt (plain build +1).
'use strict'

const fs = require('fs')
const path = require('path')
const readline = require('readline')
const { execSync } = require('child_process')

const ROOT = path.resolve(__dirname, '..')
const PKG = path.join(ROOT, 'package.json')
const CONSTANTS = path.join(ROOT, 'backend', 'core', 'constants.py')
const NSH = path.join(ROOT, 'scripts', 'flux_version.nsh')

function parse(v) {
  const m = /^(\d+)\.(\d+)\.(\d+)$/.exec(String(v).trim())
  if (!m) throw new Error(`fluxVersion invalide : "${v}" (attendu x.x.xxx)`)
  return { major: +m[1], minor: +m[2], build: +m[3] }
}

function display({ major, minor, build }) {
  return `${major}.${minor}.${String(build).padStart(3, '0')}`
}

function semver({ major, minor, build }) {
  return `${major}.${minor}.${build}`
}

function next(cur, { minor, major }) {
  if (major) return { major: cur.major + 1, minor: 0, build: 0 }
  if (minor) return { major: cur.major, minor: cur.minor + 1, build: 0 }
  return { ...cur, build: cur.build + 1 }
}

async function ask(rl, question) {
  // Enter (or anything but y/o) = N.
  const answer = await new Promise(resolve => rl.question(`${question} (y/N) : `, resolve))
  return /^\s*[yo]/i.test(answer)
}

async function choose(args) {
  if (args.includes('--major')) return { major: true, minor: false }
  if (args.includes('--minor')) return { major: false, minor: true }
  if (args.includes('--no-prompt') || !process.stdin.isTTY) return { major: false, minor: false }
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout })
  try {
    const minor = await ask(rl, 'Incrementer une version mineure ?')
    const major = await ask(rl, 'Incrementer une version majeure ?')
    return { minor, major }
  } finally {
    rl.close()
  }
}

function replaceOnce(text, regex, replacement, file) {
  if (!regex.test(text)) throw new Error(`motif de version introuvable dans ${file}`)
  return text.replace(regex, replacement)
}

function writeVersion(v) {
  const pkg = fs.readFileSync(PKG, 'utf8')
  let out = replaceOnce(pkg, /"version":\s*"[^"]*"/, `"version": "${semver(v)}"`, 'package.json')
  out = replaceOnce(out, /"fluxVersion":\s*"[^"]*"/, `"fluxVersion": "${display(v)}"`, 'package.json')
  fs.writeFileSync(PKG, out)

  const py = fs.readFileSync(CONSTANTS, 'utf8')
  fs.writeFileSync(CONSTANTS, replaceOnce(py, /APP_VERSION:\s*str\s*=\s*"[^"]*"/,
    `APP_VERSION: str = "${display(v)}"`, 'constants.py'))

  fs.writeFileSync(NSH,
    '; Generated by scripts/build.cjs on each build. Display version of FLUX (x.x.xxx).\n' +
    `!define FLUX_VERSION "${display(v)}"\n`)
}

function run(cmd, env) {
  console.log(`\n[build] ${cmd}`)
  execSync(cmd, { cwd: ROOT, stdio: 'inherit', env })
}

async function main() {
  const pkg = JSON.parse(fs.readFileSync(PKG, 'utf8'))
  const cur = parse(pkg.fluxVersion)
  const choice = await choose(process.argv.slice(2))
  const v = next(cur, choice)
  console.log(`\n[version] ${display(cur)} -> ${display(v)}`)

  const backup = [PKG, CONSTANTS, NSH].map(f => [f, fs.readFileSync(f)])
  writeVersion(v)

  const env = { ...process.env, CSC_IDENTITY_AUTO_DISCOVERY: 'false' }
  try {
    run('npm run build:frontend', env)
    run('npm run build:backend', env)
    run('npm run build:electron', env)
    run(`npx electron-builder --config scripts/electron-builder.yml "-c.nsis.artifactName=\${productName}-Setup-${display(v)}.\${ext}"`, env)
  } catch (err) {
    for (const [f, data] of backup) fs.writeFileSync(f, data)
    console.error(`\n[version] build echoue, version remise a ${display(cur)}`)
    process.exit(typeof err.status === 'number' && err.status !== 0 ? err.status : 1)
  }
  console.log(`\n[version] FLUX ${display(v)} -> INSTALLEURS\\FLUX-Setup-${display(v)}.exe`)
}

if (require.main === module) {
  main().catch(err => {
    console.error(`[build] ${err.message}`)
    process.exit(1)
  })
}

module.exports = { parse, display, semver, next }
