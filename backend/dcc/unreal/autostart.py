# autostart.py — FLUX host project + bridge plugin for Unreal Engine (ADR 0052).
#
# Unreal has no per-user startup folder like Maya / Nuke / Mari: Python startup scripts
# are found per project (Content/Python of the project and of its plugins, init_unreal.py
# runs at editor startup). So FLUX owns ONE Unreal project per machine, the "host" project
# FluxRender, kept local (%LOCALAPPDATA%: Unreal writes heavy caches next to the .uproject,
# never on OneDrive). The bridge lives in a content-only plugin of that project (no C++,
# nothing to compile). Unreal is the renderer: the shots come from the FLUX USD stages, the
# host project holds no artist work.
#
# Same interface as the other autostart modules: is_installed / get_startup_file /
# install / uninstall (exe), plus ensure_project(exe) used by the launcher.

from __future__ import annotations

import json
import os
import re
import shutil
import tempfile
from pathlib import Path

from core.logger import get_logger

log = get_logger(__name__)

_BRIDGE_SRC = Path(__file__).resolve().parent / "unreal_bridge.py"
_BRIDGE_NAME = "flux_unreal_bridge.py"
_INIT_NAME = "init_unreal.py"
_PLUGIN_NAME = "FluxBridge"
_PROJECT_NAME = "FluxRender"
_BRIDGE_LOG = Path(tempfile.gettempdir()) / "flux_unreal_bridge.log"

# Engine plugins the host project needs: USD stage, editor Python, Movie Render Queue (U4).
_PROJECT_PLUGINS = ("USDImporter", "PythonScriptPlugin", "EditorScriptingUtilities", "MovieRenderPipeline")

_INIT_SOURCE = '''# init_unreal.py - FLUX bridge autostart (written by FLUX, overwritten on install).
try:
    import flux_unreal_bridge
    flux_unreal_bridge.start()
except Exception as _flux_exc:
    import unreal
    unreal.log_error("[FLUX] Unreal bridge autostart error: %s" % _flux_exc)
'''

_UE_VERSION_RE = re.compile(r"UE_(\d+\.\d+)", re.IGNORECASE)


def project_dir() -> Path:
    """Folder of the FLUX host project (FLUX_UNREAL_PROJECT_DIR overrides, tests / studio)."""
    override = os.environ.get("FLUX_UNREAL_PROJECT_DIR")
    if override:
        return Path(override)
    local = os.environ.get("LOCALAPPDATA") or str(Path.home() / "AppData" / "Local")
    return Path(local) / "FluxPipeline" / "unreal" / _PROJECT_NAME


def project_file() -> Path:
    return project_dir() / f"{_PROJECT_NAME}.uproject"


def _python_dir() -> Path:
    return project_dir() / "Plugins" / _PLUGIN_NAME / "Content" / "Python"


def engine_association(exe_path: str | None) -> str:
    """"5.6" from ...\\UE_5.6\\Engine\\Binaries\\Win64\\UnrealEditor.exe, "" when unknown."""
    match = _UE_VERSION_RE.search(exe_path or "")
    return match.group(1) if match else ""


def _uproject_data(association: str) -> dict:
    return {
        "FileVersion": 3,
        "EngineAssociation": association,
        "Category": "",
        "Description": "FLUX render host project (generated by FLUX, holds no artist work)",
        "Plugins": [{"Name": name, "Enabled": True} for name in (*_PROJECT_PLUGINS, _PLUGIN_NAME)],
    }


def _uplugin_data() -> dict:
    return {
        "FileVersion": 3,
        "Version": 1,
        "VersionName": "1.0",
        "FriendlyName": "FLUX Bridge",
        "Description": "Socket bridge between FLUX and the Unreal editor (USD stage, reload, render).",
        "Category": "FLUX",
        "CreatedBy": "FLUX",
        "CanContainContent": True,
        "Plugins": [{"Name": "PythonScriptPlugin", "Enabled": True}, {"Name": "USDImporter", "Enabled": True}],
    }


def project_engine() -> str:
    """EngineAssociation of the host project ("" when absent or unreadable)."""
    try:
        return str(json.loads(project_file().read_text(encoding="utf-8")).get("EngineAssociation") or "")
    except (OSError, ValueError, AttributeError):
        return ""


def _write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent="\t") + "\n", encoding="utf-8")


def ensure_project(exe_path: str | None = None) -> Path:
    """Create / refresh the host project and its bridge plugin; return the .uproject.

    The engine association follows the exe FLUX launches, so a newer Unreal opens the
    project without the "convert project" dialog."""
    uproject = project_file()
    association = engine_association(exe_path)
    data = _uproject_data(association)
    if uproject.is_file():
        try:
            current = json.loads(uproject.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            current = {}
        # Keep plugins the artist may have added, make sure FLUX's are enabled.
        names = {p.get("Name") for p in current.get("Plugins", []) if isinstance(p, dict)}
        plugins = list(current.get("Plugins", [])) + [p for p in data["Plugins"] if p["Name"] not in names]
        for plugin in plugins:
            if isinstance(plugin, dict) and plugin.get("Name") in (*_PROJECT_PLUGINS, _PLUGIN_NAME):
                plugin["Enabled"] = True
        current["Plugins"] = plugins
        current.setdefault("FileVersion", 3)
        if association:
            current["EngineAssociation"] = association
        data = current
    _write_json(uproject, data)
    _install_plugin()
    return uproject


def _install_plugin() -> Path:
    plugin_root = project_dir() / "Plugins" / _PLUGIN_NAME
    _write_json(plugin_root / f"{_PLUGIN_NAME}.uplugin", _uplugin_data())
    python_dir = _python_dir()
    python_dir.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(_BRIDGE_SRC, python_dir / _BRIDGE_NAME)
    (python_dir / _INIT_NAME).write_text(_INIT_SOURCE, encoding="utf-8")
    return python_dir / _BRIDGE_NAME


def get_startup_file(exe_path: str | None = None) -> Path | None:
    return _python_dir() / _INIT_NAME


def is_installed(exe_path: str | None = None) -> bool:
    """Host project + plugin present and the bridge copy matches the FLUX source."""
    bridge = _python_dir() / _BRIDGE_NAME
    if not (project_file().is_file() and (_python_dir() / _INIT_NAME).is_file() and bridge.is_file()):
        return False
    try:
        return bridge.read_bytes() == _BRIDGE_SRC.read_bytes()
    except OSError:
        return False


def install(exe_path: str | None = None) -> dict:
    try:
        uproject = ensure_project(exe_path)
    except OSError as exc:
        return {"success": False, "message": str(exc), "path": None}
    log.info("Unreal host project + bridge -> %s", uproject)
    return {"success": True, "message": f"installed -> {uproject}", "path": str(get_startup_file())}


def uninstall(exe_path: str | None = None) -> dict:
    """Remove the bridge plugin only: the host project folder may hold Unreal caches the
    artist wants to keep (it is deleted by hand when no longer wanted)."""
    plugin_root = project_dir() / "Plugins" / _PLUGIN_NAME
    try:
        if plugin_root.exists():
            shutil.rmtree(plugin_root)
    except OSError as exc:
        return {"success": False, "message": str(exc)}
    return {"success": True, "message": "uninstalled"}


def diagnose(max_lines: int = 4) -> str:
    """Why Unreal may not answer, in words: where the bridge is and its last log lines."""
    parts = []
    if is_installed():
        parts.append(f"Bridge installe dans le projet {project_file()}")
    else:
        parts.append("Bridge non installe (Plug d'Unreal dans la barre de gauche, ou lancer Unreal depuis FLUX)")
    try:
        lines = _BRIDGE_LOG.read_text(encoding="utf-8", errors="replace").strip().splitlines()
    except OSError:
        lines = []
    if lines:
        parts.append("Log du bridge : " + " / ".join(lines[-max_lines:]))
    else:
        parts.append("Unreal n'a jamais lance le bridge : ouvrir le projet FluxRender depuis FLUX "
                     "(plugins Python Editor Script et USD Importer actives)")
    return ". ".join(parts)
